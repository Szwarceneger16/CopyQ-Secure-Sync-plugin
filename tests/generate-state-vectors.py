"""Optional independent CQSREC01 fixture oracle. NOT a runtime dependency.

All inputs, keys and nonces below are PUBLIC TEST DATA. Never pass a user's
record/key. The normal C++ tests use the frozen header without running Python.
Requires cryptography only when explicitly regenerating/checking vectors.
"""
from __future__ import annotations

import argparse
import hashlib
import struct
from pathlib import Path

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

KEY = bytes(range(32))
BINDING = b"public-state-vector-v1"
MAGIC = b"CQSREC01"
AAD = b"CopyQ-Secure-Sync-private-state-v1\0" + MAGIC + BINDING
OUTPUT = Path(__file__).resolve().parent / "fixtures" / "state_record_vectors.h"


def u64(value: int) -> bytes:
    return struct.pack(">Q", value)


def field(value: bytes) -> bytes:
    return u64(len(value)) + value


def snapshot(items: list[dict[bytes, bytes]]) -> bytes:
    return u64(len(items)) + b"".join(
        u64(len(item)) + b"".join(field(k) + field(item[k]) for k in sorted(item))
        for item in items
    )


# Opaque packed values intentionally are NOT actual CopyQ pack() serializations.
# This oracle checks storage layout, not the semantic CopyQ adapter.
SNAPSHOT = [
    {
        b"text/plain": "Zażółć gęślą jaźń\r\n🙂\0".encode("utf-8"),
        b"application/octet-stream": bytes([0, 127, 128, 255, 13, 10]),
    },
    {b"application/x-empty": b""},
]


def head(sequence: int, items: list[dict[bytes, bytes]], packed: list[bytes], parents_override=None) -> bytes:
    assert len(items) == len(packed)
    device = b"mint-lab"
    identity = device + b"/" + f"{sequence:012d}".encode("ascii")
    parents = ([] if sequence == 1 else [b"mint-lab/000000000001"]) if parents_override is None else parents_override
    return (
        field(identity) + field(device) + u64(sequence)
        + u64(len(parents)) + b"".join(field(parent) for parent in parents)
        + u64(128 if items else 40)  # bounded, synthetic source-event byte count
        + u64(len(packed)) + b"".join(field(item) for item in packed)
        + snapshot(items)
    )


def records() -> dict[str, bytes]:
    base = u64(1) + field(BINDING)
    original = head(1, SNAPSHOT, [b"AAE=", b""])
    deletion = head(2, [], [])
    tips=[b"mint-lab/000000000001",b"remote-pc/000000000001"]
    result = {
        "empty": base + u64(0) + b"\0\0",
        "pending_join": base + u64(1) + b"\0\1\0" + original + snapshot([]),
        "pending_restore": base + u64((1 << 63) + 5) + b"\1" + original
        + b"\1\1" + deletion + snapshot(SNAPSHOT),
        "checkpoint": base + u64((1 << 64) - 1) + b"\1" + original + b"\0",
        "unified_pending": u64(2) + field(BINDING) + u64(7) + b"\1" + original
        + b"\1\0" + deletion + snapshot(SNAPSHOT) + snapshot([])
        + field(hashlib.sha256(b"CopyQ-Secure-Sync-key-identity-v1\0" + KEY).hexdigest().encode()),
        "seed_pending": u64(3) + field(BINDING) + u64(8) + b"\0\0" + snapshot(SNAPSHOT)
        + field(hashlib.sha256(b"CopyQ-Secure-Sync-key-identity-v1\0" + KEY).hexdigest().encode())
        + u64(1) + b"\1" + original + field(b"public-codec-only-ciphertext")
        + b"\1" + snapshot(SNAPSHOT),
        "publication_pending": u64(4) + field(BINDING) + u64(9) + b"\1" + original
        + b"\0" + snapshot([])
        + field(hashlib.sha256(b"CopyQ-Secure-Sync-key-identity-v1\0" + KEY).hexdigest().encode())
        + u64(2) + b"\1" + deletion + field(b"public-update-codec-only-ciphertext")
        + b"\1" + snapshot(SNAPSHOT),
        "resolution_pending": u64(5) + field(BINDING) + u64(10) + b"\1" + original + b"\0" + snapshot(SNAPSHOT)
        + field(hashlib.sha256(b"CopyQ-Secure-Sync-key-identity-v1\0" + KEY).hexdigest().encode())
        + u64(2) + b"\1" + head(2, [], [], tips) + field(b"public-resolution-codec-only-ciphertext") + b"\0"
        + u64(1) + snapshot(SNAPSHOT) + b"\1" + u64(2) + b"".join(field(tip) for tip in tips),
    }
    # Schema 6 appends sorted fingerprints, keeping every historical vector intact.
    result["witnessed_pending"] = (u64(6) + result["resolution_pending"][8:]
        + u64(2) + field(b"mint-lab/000000000001") + field(bytes([0x42])*32)
        + field(b"remote-pc/000000000001") + field(bytes([0x43])*32))
    return result


def literal(value: bytes) -> str:
    encoded = value.hex()
    return "\n".join(f'    "{encoded[i:i+96]}"' for i in range(0, len(encoded), 96))


def generate() -> str:
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tests/generate-state-vectors.py. PUBLIC TEST DATA ONLY.",
        "// Independent Python struct/AESGCM oracle; no C++ codec was called.",
        "#pragma once",
        "namespace state_vectors {",
    ]
    for index, (name, plain) in enumerate(records().items()):
        nonce = bytes(range(index * 12, index * 12 + 12))
        wire = MAGIC + nonce + AESGCM(KEY).encrypt(nonce, plain, AAD)
        assert AESGCM(KEY).decrypt(nonce, wire[20:], AAD) == plain
        lines += [
            f"// {name}: wire SHA-256 {hashlib.sha256(wire).hexdigest()}",
            f"inline constexpr char {name}_plain[] =", literal(plain) + ";",
            f"inline constexpr char {name}_wire[] =", literal(wire) + ";",
        ]
    lines += ["} // namespace state_vectors", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--check", action="store_true", help="compare frozen header without modifying it")
    modes.add_argument("--write", action="store_true", help="explicitly regenerate the public fixture header")
    modes.add_argument("--verify-cpp", type=Path, help="verify hex emitted by the C++ test's public-checkpoint mode")
    args = parser.parse_args()
    if args.verify_cpp:
        # Only this small, known public record is allowed. Bound reads first.
        with args.verify_cpp.open("rb") as stream:
            text = stream.read(16385)
        if len(text) > 16384:
            raise SystemExit("Oversized test output")
        wire = bytes.fromhex(text.decode("ascii"))
        if len(wire) < 36 or wire[:8] != MAGIC:
            raise SystemExit("Unexpected test envelope")
        decoded = AESGCM(KEY).decrypt(wire[8:20], wire[20:], AAD)
        if decoded != records()["checkpoint"]:
            raise SystemExit("C++ output differs from the independent public checkpoint")
        print("CPP_CHECKPOINT_VERIFIED_BY_PYTHON")
    elif args.write:
        OUTPUT.write_bytes(generate().encode("ascii"))
        print("Public fixture header regenerated")
    else:
        if OUTPUT.read_bytes() != generate().encode("ascii"):
            raise SystemExit("Frozen state vectors differ from the independent oracle")
        print("STATE_VECTORS_MATCH_INDEPENDENT_ORACLE")


if __name__ == "__main__":
    main()
